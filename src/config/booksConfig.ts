/**
 * 书籍（丛书）配置。
 *
 * 一本书是「内容之上的一层」：书名、简介、篇/章大纲都放这里；
 * 正文仍在文章里（frontmatter 的 `series` + `seriesOrder` 指到对应条目），
 * 书页按 `order` 把两边对上 —— 目录来自本文件，链接与字数来自文章。
 *
 * 为什么章节标题要在这里再写一遍：
 * ① 目录要能一次画全（将来有「只有标题、还没写」的条目时，没有文章也得显示）；
 * ② 篇的归属没法放在文章上 —— postSchema 里没有 part 字段，硬塞会被 zod 丢掉。
 * 现在全书都写完了，两处标题一致；改标题时以文章为准，这里只是兜底。
 *
 * 新增一本书：在 booksConfig 里加一项，然后给文章写上 series / seriesOrder 即可，
 * 页面（/books/<id>/）会自动生成。
 */

export interface BookEntry {
	/** 与文章 frontmatter 的 seriesOrder 对应；可以带小数（如附表用 5.5 排在两章之间） */
	order: number;
	/** 目录里显示的编号：序 / 第 01 章 / 附 / 后记 */
	label: string;
	title: string;
	/** 标题下一行的一句话摘要 */
	summary?: string;
}

export interface BookPart {
	/** 第一篇 */
	name: string;
	/** 认知篇 */
	title: string;
	/** 篇副标题，取自该书原稿的篇首语标题 */
	subtitle: string;
	/** 篇首语所在的 spec 条目 id —— 篇首语没有详情页，只在书页内折叠展开 */
	introId: string;
	entries: BookEntry[];
}

export interface BookConfig {
	/** 路由用：/books/<id>/ */
	id: string;
	/** 内部标识与匹配用：文章的 series 字段要和它一致 */
	title: string;
	/**
	 * 完整书名（含副书名），用于分享海报、分享文案这类「要写全名」的场合。
	 * 不填则等于 title。书页 h1 仍用 title + kicker 分层显示，不读这个字段。
	 */
	fullTitle?: string;
	/** 书名字上方那行小字 */
	kicker: string;
	/** 一句话定位（大字） */
	lead: string;
	/** 书页「关于这本书」里的一句引文；不填就不显示这一行 */
	quote?: string;
/** 刊头金句不在这里配：与其它合集页共用 src/data/banner-quotes.md 的同一份金句集 */
	/** 简介 */
	description: string;
	/** 封面图；留空则用排版封面（竖排书名） */
	cover?: string;
	/**
	 * 分享海报里竖版书封的裁切重心（0 = 顶部，1 = 底部），默认 0.72。
	 * 海报封面区是 1.7:1 的横框，3:4 的书封放进去要上下裁掉一半多，
	 * 只能让「书名所在的那一段」落在框里：见山的书名在底部，用 0.72；
	 * 增长黑客的名字在顶部，用 0。
	 */
	posterFocus?: number;
	/**
	 * 书页顶部的背景横幅；留空则用全局壁纸。
	 * 只影响这一本书的书页，不影响首页、文章页或其他书。
	 */
	banner?: string;
	preface?: BookEntry;
	parts: BookPart[];
	afterword?: BookEntry;
}

